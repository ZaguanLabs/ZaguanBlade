export const availableThemes: AppTheme[] = [zaguanDarkTheme, bladeCoderTheme, nebulaDustTheme, bladeCreamTheme, alpineFrostTheme, bladeRobotTheme];

export const defaultThemeId = zaguanDarkTheme.id;

const legacyThemeIdMap: Record<string, string> = {
    system: defaultThemeId,
    dark: defaultThemeId,
    default: defaultThemeId,
    zaguan: defaultThemeId,
};

export function normalizeThemeId(themeId?: string | null): string {
    const trimmed = themeId?.trim();
    if (!trimmed) return defaultThemeId;
    const normalized = legacyThemeIdMap[trimmed] ?? trimmed;
    return availableThemes.some((theme) => theme.id === normalized) ? normalized : defaultThemeId;
}

export function getThemeById(themeId?: string | null): AppTheme {
    const normalized = normalizeThemeId(themeId);
    return availableThemes.find((theme) => theme.id === normalized) ?? zaguanDarkTheme;
}

export function applyThemeToDocument(themeId?: string | null) {
    if (typeof document === 'undefined') return;

    const theme = getThemeById(themeId);
    const root = document.documentElement;
    root.dataset.theme = theme.id;
    root.style.colorScheme = theme.appearance;

    Object.entries(theme.tokens).forEach(([token, value]) => {
        root.style.setProperty(token, value);
    });
}
